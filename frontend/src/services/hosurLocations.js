/**
 * Filter local database with fuzzy token match
 */
export function filterLocationSuggestions(searchText) {
  if (!searchText || !searchText.trim()) {
    return [
      HOSUR_LOCATIONS_DATABASE.find(l => l.name === "Golden Fairmart") || HOSUR_LOCATIONS_DATABASE[0],
      { name: "Hosur Bus Stand", subtitle: "Central Hosur, Tamil Nadu", category: "Hosur Central" },
      { name: "SIPCOT Phase 1", subtitle: "Industrial Area, Hosur", category: "SIPCOT Industrial" },
      { name: "SIPCOT Phase 2", subtitle: "Industrial Complex, Hosur", category: "SIPCOT Industrial" },
      { name: "Mathigiri", subtitle: "Hosur, Tamil Nadu", category: "Hosur Area" },
      { name: "KCC Nagar", subtitle: "Nallur, Hosur, Tamil Nadu", category: "Residential Area" },
      { name: "Attibele Border & Toll Plaza", subtitle: "Bengaluru Border (~8 Kms)", category: "Near Hosur" },
      { name: "Electronic City Phase 1", subtitle: "Bengaluru (~28 Kms)", category: "Bengaluru Hub" },
      { name: "Krishnagiri Town", subtitle: "Tamil Nadu (55 Kms)", category: "Intercity Route" },
    ].filter(Boolean)
  }

  const query = searchText.trim().toLowerCase()
  const cleanQ = query.replace(/[^a-z0-9\s]/g, " ").replace(/\s+/g, " ").trim()
  const qTokens = cleanQ.split(" ").filter(Boolean)

  const exactStarts = []
  const wordStarts = []
  const containsMatches = []

  HOSUR_LOCATIONS_DATABASE.forEach((item) => {
    const nameLow = item.name.toLowerCase()
    const subLow = item.subtitle.toLowerCase()
    const catLow = item.category.toLowerCase()
    const allText = `${nameLow} ${subLow} ${catLow}`

    if (nameLow.startsWith(query) || nameLow.startsWith(cleanQ)) {
      exactStarts.push(item)
    } else if (
      nameLow.split(/[\s,/-]+/).some((w) => w.startsWith(query) || (qTokens[0] && w.startsWith(qTokens[0]))) ||
      subLow.split(/[\s,/-]+/).some((w) => w.startsWith(query) || (qTokens[0] && w.startsWith(qTokens[0])))
    ) {
      wordStarts.push(item)
    } else if (
      nameLow.includes(query) ||
      subLow.includes(query) ||
      catLow.includes(query) ||
      qTokens.every((tok) => allText.includes(tok))
    ) {
      containsMatches.push(item)
    }
  })

  const combined = [...exactStarts, ...wordStarts, ...containsMatches]
  const seen = new Set()
  const result = []
  for (const it of combined) {
    if (!seen.has(it.name.toLowerCase())) {
      seen.add(it.name.toLowerCase())
      result.push(it)
    }
    if (result.length >= 9) break
  }

  // If user typed custom text that didn't match local list, ensure candidate is present immediately
  if (result.length === 0 && cleanQ.length >= 2) {
    result.push({
      name: toTitleCase(searchText.trim()),
      subtitle: "Hosur, Tamil Nadu",
      category: "Hosur Location",
      fullAddress: formatExactLocation(searchText),
    })
  }

  return result
}

// SECURITY: a real Google Maps API key used to be hardcoded here as a
// fallback. A key committed to source ships in every built bundle AND sits
// in git history, and because it was a *fallback* it kept working even
// where the deployment intended a different key -- so a misconfigured
// environment silently billed the wrong project instead of failing
// visibly. The key now comes only from the environment
// (VITE_GOOGLE_MAPS_KEY / VITE_GOOGLE_MAPS_API_KEY, see
// frontend/.env.example). With none set, place search degrades to the
// Photon and Nominatim tiers below, which need no key.
//
// Removing it here does NOT un-leak it: the value is still in git history
// and in any bundle already shipped. It must be rotated in the Google
// Cloud console, and the replacement restricted by HTTP referrer and by
// API (Geocoding + Distance Matrix only).
const GOOGLE_API_KEY =
  (typeof import.meta !== "undefined" && import.meta.env
    ? import.meta.env.VITE_GOOGLE_MAPS_KEY || import.meta.env.VITE_GOOGLE_MAPS_API_KEY
    : "") || ""

function toTitleCase(str) {
  return (str || "")
    .split(" ")
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(" ")
}

// In-memory cache for dynamic geocoding
const onlineSearchCache = new Map()

/**
 * Fetch dynamic places from Google Maps Geocoding API (primary) or Photon/OSM (fallback) biased to Hosur
 */
export async function searchHosurPlacesOnline(query) {
  if (!query || !query.trim() || query.trim().length < 2) return []
  const q = query.trim().toLowerCase()
  if (onlineSearchCache.has(q)) return onlineSearchCache.get(q)

  const searchQuery = q.includes("hosur") ? q : `${q}, Hosur, Tamil Nadu`

  // 1. Try Google Maps Geocoding API
  if (GOOGLE_API_KEY) {
    try {
      const url = `https://maps.googleapis.com/maps/api/geocode/json?address=${encodeURIComponent(
        searchQuery
      )}&key=${GOOGLE_API_KEY}&bounds=12.60,77.70|12.95,78.10&components=country:IN&language=en`
      const res = await fetch(url)
      if (res.ok) {
        const data = await res.json()
        if (data.status === "OK" && data.results && data.results.length > 0) {
          const results = data.results
            .filter((r) => {
              const fa = (r.formatted_address || "").toLowerCase()
              return (
                fa.includes("hosur") ||
                fa.includes("tamil nadu") ||
                fa.includes("krishnagiri") ||
                fa.includes("bengaluru") ||
                fa.includes("attibele") ||
                fa.includes("anekal")
              )
            })
            .map((item) => {
              const fa = item.formatted_address || ""
              const parts = fa.split(",").map((s) => s.trim())
              const rawTitle = toTitleCase(q)
              const firstPart = parts[0] || rawTitle
              const name = firstPart.length < 35 ? firstPart : rawTitle
              const subtitle = parts.slice(1, 4).join(", ") || "Hosur, Tamil Nadu"
              return {
                name: name.toLowerCase().includes(q) ? name : `${toTitleCase(q)} (${firstPart})`,
                subtitle,
                category: "Live Location",
                fullAddress: fa.includes(name) ? fa : `${name}, ${fa}`,
                lat: item.geometry?.location?.lat,
                lng: item.geometry?.location?.lng,
              }
            })

          if (results.length > 0) {
            onlineSearchCache.set(q, results)
            return results
          }
        }
      }
    } catch (err) {
      console.debug("[HosurLocationSearch] Google API fetch error:", err)
    }
  }

  // 2. Fallback: Photon (Komoot OSM geocoder with Hosur coordinates bias)
  try {
    const photonUrl = `https://photon.komoot.io/api/?q=${encodeURIComponent(
      q
    )}&lat=12.7409&lon=77.8253&limit=6`
    const res = await fetch(photonUrl)
    if (res.ok) {
      const data = await res.json()
      const features = data.features || []
      const results = features
        .map((f) => {
          const p = f.properties || {}
          const name = p.name || toTitleCase(q)
          const street = p.street || p.locality || p.district || ""
          const city = p.city || "Hosur"
          const state = p.state || "Tamil Nadu"
          const subtitle = [street, city, state].filter(Boolean).join(", ")
          return {
            name,
            subtitle,
            category: (p.osm_value || "LOCATION").toUpperCase(),
            fullAddress: `${name}, ${subtitle}`,
            lat: f.geometry?.coordinates?.[1],
            lng: f.geometry?.coordinates?.[0],
          }
        })
        .filter((r) => r.name)

      if (results.length > 0) {
        onlineSearchCache.set(q, results)
        return results
      }
    }
  } catch (err) {
    console.debug("[HosurLocationSearch] Photon search fallback failed:", err)
  }

  // 3. Fallback: OpenStreetMap Nominatim
  try {
    const nomUrl = `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(
      searchQuery
    )}&format=json&addressdetails=1&countrycodes=in&limit=6`
    const res = await fetch(nomUrl, { headers: { "Accept-Language": "en" } })
    if (res.ok) {
      const data = await res.json()
      const results = data.map((item) => {
        const parts = item.display_name.split(",").map((s) => s.trim())
        const name = parts[0]
        const subtitle = parts.slice(1, 4).join(", ") || "Hosur, Tamil Nadu"
        return {
          name,
          subtitle,
          category: item.type ? item.type.toUpperCase() : "LOCATION",
          fullAddress: item.display_name,
          lat: parseFloat(item.lat),
          lng: parseFloat(item.lon),
        }
      })
      onlineSearchCache.set(q, results)
      return results
    }
  } catch (err) {
    console.debug("[HosurLocationSearch] Nominatim search fallback failed:", err)
  }

  // 4. If all online APIs fail or return 0, do NOT synthesize a location without coordinates.
  // Returning an empty array forces the caller/UI to require a geocoded selection.
  onlineSearchCache.set(q, [])
  return []
}

const coordCache = new Map()

/**
 * Resolve real coordinates for a location the customer selected.
 *
 * Why this exists: only 9 of the ~71 entries in HOSUR_LOCATIONS_DATABASE
 * carry hand-authored lat/lng. Picking any of the other 62 -- or typing a
 * free-text address -- produced a booking with NO coordinate, which is
 * what the hardcoded Hosur town-centre fallback in the booking pages was
 * papering over. That fake point then drove the server-side zone gate,
 * distance-based dispatch, the route measurement and therefore the fare.
 *
 * The fix is deliberately NOT a hand-typed coordinate table for the
 * remaining 62 entries. Coordinates invented from memory would look
 * authoritative while being wrong, and wrong coordinates are worse than
 * none here precisely because so much depends on them. Instead this
 * resolves them for real, from the same geocoding providers the online
 * search already uses (Google Geocoding, then Photon, then Nominatim),
 * and caches the answer for the session.
 *
 * Returns { lat, lng } or null. Callers must treat null as "we do not
 * know where this is" and refuse to guess.
 */
export async function resolveLocationCoords(locOrText) {
  if (!locOrText) return null

  // Already carries real coordinates (an online suggestion, or one of the
  // authored entries) -- nothing to resolve.
  if (typeof locOrText === "object" && locOrText.lat != null && locOrText.lng != null) {
    return { lat: Number(locOrText.lat), lng: Number(locOrText.lng) }
  }

  const address = typeof locOrText === "object"
    ? (locOrText.fullAddress || locOrText.name || "")
    : String(locOrText)
  if (!address.trim()) return null

  const key = address.trim().toLowerCase()
  if (coordCache.has(key)) return coordCache.get(key)

  // The online place search already returns lat/lng from whichever
  // provider answers, so reuse it rather than adding a fourth code path.
  try {
    const results = await searchHosurPlacesOnline(address)
    const hit = (results || []).find((r) => r.lat != null && r.lng != null)
    if (hit) {
      const coords = { lat: Number(hit.lat), lng: Number(hit.lng) }
      coordCache.set(key, coords)
      return coords
    }
  } catch (err) {
    console.debug("[HosurLocations] coordinate resolution failed:", err)
  }

  coordCache.set(key, null)
  return null
}


/**
 * Format exact location text when user selects or enters a destination
 */
export function formatExactLocation(locOrText) {
  if (!locOrText) return ""
  if (typeof locOrText === "object") {
    if (locOrText.fullAddress) return locOrText.fullAddress
    const sub = locOrText.subtitle ? locOrText.subtitle.split("(")[0].trim().replace(/,\s*$/, "") : ""
    const base = sub ? `${locOrText.name}, ${sub}` : locOrText.name
    if (
      base.toLowerCase().includes("hosur") ||
      base.toLowerCase().includes("tamil nadu") ||
      base.toLowerCase().includes("bengaluru") ||
      base.toLowerCase().includes("karnataka")
    ) {
      return base
    }
    return `${base}, Hosur, Tamil Nadu`
  }

  const raw = String(locOrText).trim()
  if (
    raw.toLowerCase().includes("hosur") ||
    raw.toLowerCase().includes("tamil nadu") ||
    raw.toLowerCase().includes("bengaluru") ||
    raw.toLowerCase().includes("karnataka")
  ) {
    return raw
  }
  return `${toTitleCase(raw)}, Hosur, Tamil Nadu`
}

